KANJI = {'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10,'半':0.5}
def to_months(num, unit):
    n = KANJI.get(num) if num in KANJI else float(num)
    if n is None: return None
    if unit in ('日','営業日'): return n/30
    if unit=='週間': return n/4.3
    if unit=='年': return n*12
    return n  # か月系

def period_bucket(m):
    if m is None: return None
    if m<=1.05: return '1か月以内'
    if m<=6.1: return '〜半年'
    if m<=12.1: return '〜1年'
    return '1年以上'

def scope_text(c, scope):
    if scope=='before': return T(c,'challengeDetail','summary')
    if scope=='after':  return T(c,'actions','resultsQualitative')
    return T(c,'title','summary','challengeDetail','actions','resultsQualitative')

def tag_case(c):
    out = {}
    for axis, rules in AXES.items():
        vals = []
        for val, pat, scope in rules:
            txt = scope_text(c, scope)
            if axis=='期間':
                months = []
                for m in re.finditer(pat, txt):
                    g = m.groups()
                    # グループから数値と単位を拾う
                    nums = [x for x in g if x and re.fullmatch(r'\d+|[一二三四五六七八九十]+|半', x)]
                    units = [x for x in g if x and re.fullmatch(r'か月|ヶ月|カ月|ヵ月|ケ月|週間|営業日|日|年', x)]
                    if nums and units:
                        mo = to_months(nums[0], units[0])
                        if mo is not None and mo<=60: months.append(mo)
                # scale 項目に導入期間があれば優先
                for s in (c.get('scale') or []):
                    if re.search(r'(導入|構築|移行|開発|支援|プロジェクト|展開|立ち上げ)期間', s.get('metric','')):
                        mm = re.search(r'(\d+|[一二三四五六七八九十]+|半)\s*(か月|ヶ月|カ月|ヵ月|ケ月|週間|営業日|日|年)', s.get('value',''))
                        if mm: months.insert(0, to_months(mm.group(1), mm.group(2)))
                if months:
                    b = period_bucket(months[0])
                    if b: vals.append(b)
            elif re.search(pat, txt):
                vals.append(val)
        out[axis] = vals
    return out

def main():
    cs = json.load(open(CASES, encoding='utf-8'))
    if len(sys.argv)>2 and sys.argv[1]=='--sample':
        axis = sys.argv[2]; random.seed(7)
        for val, pat, scope in AXES[axis]:
            hits=[]
            for c in cs:
                txt=scope_text(c,scope); m=re.search(pat,txt)
                if m: hits.append((c,txt,m))
            print(f'\n== {axis} / {val}  n={len(hits)}')
            for c,txt,m in random.sample(hits,min(7,len(hits))):
                i=m.start(); print('  ['+c["id"][:28]+'] …'+txt[max(0,i-35):i+45].replace('\n',' ')+'…')
        return
    axes = {c['id']: tag_case(c) for c in cs}
    json.dump(axes, open(OUT,'w',encoding='utf-8'), ensure_ascii=False, indent=0)
    print(f'wrote {OUT} ({len(axes)} cases)\n')
    print('軸 | 値あり件数 | 値が1つに定まる件数 | 値の内訳')
    for axis in AXES:
        filled=[v[axis] for v in axes.values() if v[axis]]
        single=[v for v in filled if len(set(v))==1]
        dist=collections.Counter(x for v in filled for x in set(v))
        print(f'{axis} | {len(filled)} | {len(single)} | '+', '.join(f'{k}:{n}' for k,n in dist.most_common()))

if __name__=='__main__':
    main()
