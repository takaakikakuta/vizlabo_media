/** 虎の巻をテキストにする（「テキストで保存」用）。purposes は選ばれた目的（主目的が先頭）。 */
export function buildObjectionsText(purposes: { slug: string; label: string }[]): string {
  const L: string[] = ["■ 断られたときの虎の巻", ""];
  L.push("▼ あなたの目的なら、ここまで譲れます");
  for (const p of purposes) {
    const c = CONCESSIONS[p.slug];
    if (!c) continue;
    L.push(`「${p.label}」`, `  社名を伏せる場合：${c.name}`, `  数字を出せない場合：${c.number}`, `  これだけは残す：${c.keep}`);
  }
  L.push("");
  for (const st of OBJECTION_STAGES) {
    L.push(`▼ ${st.label}`, "");
    for (const o of st.items) {
      L.push(`「${o.say}」`, `  相手の事情：${o.real}`, `  返し方：${o.reply}`, "  落としどころ：");
      o.options.forEach((x, i) => L.push(`    ${i + 1}. ${x}`));
      L.push("");
    }
  }
  return L.join("\n");
}
