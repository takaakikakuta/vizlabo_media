/** 2課題の“なぜ繋がるか”。用意がなければ汎用文にフォールバック。 */
export function bridgeText(a: string, b: string): string {
  return (
    BRIDGES[key(a, b)] ??
    `「${challengeLabel(a)}」を解決した企業は、「${challengeLabel(b)}」も一緒に解決している傾向があります。あわせて考えると打ち手が広がります。`
  );
}
